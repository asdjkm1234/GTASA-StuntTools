/**
 * Render a plugin's generated header from its catalogue — the fingerprint constants (DISK file
 * anchors) + the per-patch byte-verify anchors (runtime addresses), as compile-time C++ constants.
 * The C++ framework never hard-codes an address; it reads these tables. A malformed catalogue is a
 * hard error here (generate time), not a garbage write at runtime. Each plugin keeps a thin
 * `gen/generate.ts` that calls `renderHeader` with its catalogue, namespace and output path.
 */

import type { CatalogueEntry, FileAnchor, Fingerprint } from './catalogue';

export interface RenderOptions {
  /** The plugin's C++ namespace; constants are emitted into `<namespace>::gen` (perfect-map passes `pm`). */
  readonly namespace: string;
}

/** Render the full generated-header text. Pure — takes the catalogue + fingerprint, returns the header. */
export function renderHeader(
  catalogue: readonly CatalogueEntry[],
  fingerprint: Fingerprint,
  options: RenderOptions,
): string {
  validate(catalogue, fingerprint);

  const ns = `${options.namespace}::gen`;
  const lines: string[] = [
    '#pragma once',
    '// AUTO-GENERATED by gen/generate.ts from gen/catalogue.ts — DO NOT EDIT.',
    '#include <cstdint>',
    '',
    '#include <asi/generated-tables.hpp>',
    '',
    `namespace ${ns} {`,
    '',
    '// The framework owns the anchor types (asi::ByteAnchor / asi::FileAnchor); the tables below are emitted',
    '// AS those types, so a plugin hands them over directly — no cast, no parallel struct to drift.',
    '',
    '// ---- fingerprint (the version gate, read from the exe on disk) ----',
    `inline constexpr uint32_t kExeSize = ${fingerprint.exeSize}u;`,
    `inline constexpr char kExeSha1[] = "${fingerprint.sha1}";`,
    '',
  ];

  const emitBytes = (sym: string, bytes: readonly number[]): void => {
    lines.push(`inline constexpr uint8_t ${sym}[] = {${byteList(bytes)}};`);
  };

  const fpRows = fingerprint.anchors.map((anchor: FileAnchor): string => {
    const sym = `kFp_${ident(anchor.name)}`;
    emitBytes(sym, anchor.bytes);

    return `  {"${anchor.name}", 0x${anchor.fileOffset.toString(16)}u, ${sym}, ${anchor.bytes.length}u},`;
  });
  lines.push('', 'inline constexpr asi::FileAnchor kFingerprint[] = {', ...fpRows, '};');
  lines.push(`inline constexpr uint32_t kFingerprintCount = ${fingerprint.anchors.length}u;`, '');

  lines.push('// ---- patch sites (runtime byte-verify; apply is hand-written in src/patches/) ----');
  const siteRows: string[] = [];
  for (const entry of catalogue) {
    for (const site of entry.sites) {
      const sym = `kSite_${ident(entry.id)}_${ident(site.name)}`;
      emitBytes(sym, site.bytes);
      siteRows.push(`  {"${site.name}", 0x${site.address.toString(16)}u, ${sym}, ${site.bytes.length}u},`);
    }
  }
  lines.push('', 'inline constexpr asi::ByteAnchor kPatchSites[] = {', ...siteRows, '};');
  lines.push(`inline constexpr uint32_t kPatchSiteCount = ${siteRows.length}u;`, '');
  lines.push(`}  // namespace ${ns}`, '');

  return lines.join('\n');
}

function byteList(bytes: readonly number[]): string {
  return bytes.map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ');
}

function checkBytes(name: string, bytes: readonly number[]): void {
  if (bytes.length === 0) {
    throw new Error(`anchor ${name}: empty byte sequence`);
  }
  if (bytes.some((b) => !Number.isInteger(b) || b < 0 || b > 0xff)) {
    throw new Error(`anchor ${name}: bytes must be 0..255`);
  }
}

/** Sanitize a catalogue name/id into a valid C identifier fragment. */
function ident(value: string): string {
  return value.replace(/[^a-z0-9]/gi, '_');
}

/** Throw on anything that would produce an unsafe or malformed header. */
function validate(catalogue: readonly CatalogueEntry[], fingerprint: Fingerprint): void {
  if (!/^[0-9a-f]{40}$/.test(fingerprint.sha1)) {
    throw new Error(`fingerprint sha1 must be 40 lowercase hex chars: ${fingerprint.sha1}`);
  }
  if (!Number.isInteger(fingerprint.exeSize) || fingerprint.exeSize <= 0) {
    throw new Error(`fingerprint exeSize must be a positive integer: ${fingerprint.exeSize}`);
  }
  if (fingerprint.anchors.length === 0) {
    throw new Error('fingerprint needs at least one anchor');
  }
  for (const anchor of fingerprint.anchors) {
    if (!Number.isInteger(anchor.fileOffset) || anchor.fileOffset < 0 || anchor.fileOffset >= fingerprint.exeSize) {
      throw new Error(
        `fingerprint anchor ${anchor.name}: fileOffset out of range: 0x${anchor.fileOffset.toString(16)}`,
      );
    }
    checkBytes(anchor.name, anchor.bytes);
  }
  for (const site of catalogue.flatMap((entry) => entry.sites)) {
    if (!Number.isInteger(site.address) || site.address < 0x400000 || site.address > 0x2000000) {
      throw new Error(`site ${site.name}: address out of the 1.0 US range: 0x${site.address.toString(16)}`);
    }
    checkBytes(site.name, site.bytes);
  }
  const ids = catalogue.map((entry) => entry.id);
  if (new Set(ids).size !== ids.length) {
    throw new Error(`duplicate catalogue id: ${ids.join(', ')}`);
  }
  // Site names are a LOOKUP KEY at runtime (asi::FindSite), so a duplicate is not cosmetic: the framework would
  // hand a patch the first match's bytes and address, which for a trampoline means relocating a foreign
  // instruction. Verification cannot catch it — the site it picked really is pristine.
  const siteNames = catalogue.flatMap((entry) => entry.sites).map((site) => site.name);
  if (new Set(siteNames).size !== siteNames.length) {
    throw new Error(`duplicate site name (they are FindSite keys): ${siteNames.join(', ')}`);
  }
  const anchorNames = fingerprint.anchors.map((anchor) => anchor.name);
  if (new Set(anchorNames).size !== anchorNames.length) {
    throw new Error(`duplicate fingerprint anchor name: ${anchorNames.join(', ')}`);
  }
}
